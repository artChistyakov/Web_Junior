/* ==========================================================================
   АКТИВНИЙ КОД (Сучасний варіант закриття по кліку на фон)
   ========================================================================== */

// Головне правило jQuery: чекаємо, поки весь HTML завантажиться і буде готовий до роботи
$(document).ready(function(){
	
	// 1. ЛОГІКА ВІДКРИТТЯ КАРТИНКИ
	// Знаходимо всі наші мініатюри (блоки з класом .item) і "слухаємо" подію кліку на будь-який з них
	$(".item").on('click', function(){
		
		// НАЙВАЖЛИВІШИЙ РЯДОК! Розбираємо його по кроках:
		// $(this) - це саме той ОДИН блок .item, на який користувач щойно клікнув (а не всі 12 одразу).
		// .children("img") - ми заглядаємо всередину цього блоку і знаходимо там тег <img>.
		// .attr("src") - ми беремо в цієї картинки її адресу (наприклад, "Images/5.jpg").
		// І зберігаємо цю адресу у змінну з назвою src.
		let src = $(this).children("img").attr("src");
		
		// Тепер ми знаходимо порожній тег <img>, який лежить у нашому прихованому оверлеї,
		// і за допомогою методу .attr() ПІДСТАВЛЯЄМО туди ту адресу, яку ми щойно скопіювали.
		// Тобто ми "зарядили" велику рамку потрібною фотографією.
		$(".overlay img").attr("src", src);
		
		// Картинка готова, тепер треба її показати! 
		// Ми додаємо до оверлею клас "open". Згадаймо CSS: цей клас змінює display: none на display: flex,
		// і темна штора з великою картинкою ефектно з'являється на екрані.
		$(".overlay").addClass("open");
	});

	// 2. ЛОГІКА ЗАКРИТТЯ КАРТИНКИ
	// Ми "слухаємо" клік по самому темному фону (оверлею)
	$(".overlay").on('click', function(){
		// Якщо користувач клікнув кудись по темному екрану — ми просто забираємо клас "open".
		// CSS знову робить display: none, і штора миттєво зникає.
		$(".overlay").removeClass("open");
	});
});
